const MS_PER_DAY = 86400000;
const yearTriviaCache = new Map();

function isLeapYear(year) {
  return (year % 4 === 0 && year % 100 !== 0) || year % 400 === 0;
}

function getDaysInYear(year) {
  return isLeapYear(year) ? 366 : 365;
}

function mulberry32(seed) {
  let a = seed >>> 0;
  return function nextRandom() {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function buildBasePermutation(year) {
  const seed = (Math.imul(year | 0, 0x9e3779b1) ^ 0x517cc1b7) >>> 0;
  const rand = mulberry32(seed);
  const perm = Array.from({ length: triviaQuestions.length }, (_, i) => i);
  for (let i = perm.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    const tmp = perm[i];
    perm[i] = perm[j];
    perm[j] = tmp;
  }
  return perm;
}

function collectLast7Indices(totalItems, daysInYear, count) {
  const tailSlots = new Set();
  for (let d = Math.max(1, daysInYear - 6); d <= daysInYear; d++) {
    const start = (d - 1) * count;
    for (let k = 0; k < count; k++) {
      tailSlots.add((start + k) % totalItems);
    }
  }
  return tailSlots;
}

function getYearTriviaPermutation(year, count) {
  const safeCount = Math.max(1, Math.min(triviaQuestions.length, Math.floor(count || 3)));
  const cacheKey = `${year}:${safeCount}`;
  const cached = yearTriviaCache.get(cacheKey);
  if (cached) return cached;

  const perm = buildBasePermutation(year);
  const total = perm.length;
  const prevPerm = buildBasePermutation(year - 1);
  const prevDays = getDaysInYear(year - 1);
  const prevTailSlots = collectLast7Indices(total, prevDays, safeCount);
  const prevLast7Values = new Set();
  for (const slot of prevTailSlots) {
    prevLast7Values.add(prevPerm[slot]);
  }

  const first7Count = Math.min(total, 7 * safeCount);
  const thisTailSlots = collectLast7Indices(total, getDaysInYear(year), safeCount);

  // Swap collisions in the first 7 days of year Y with safe non-tail slots
  // so year Y's own final 7 days remain identical to buildBasePermutation(year).
  let swapCursor = first7Count;
  for (let i = 0; i < first7Count; i++) {
    if (prevLast7Values.has(perm[i])) {
      while (
        swapCursor < total &&
        (thisTailSlots.has(swapCursor) || prevLast7Values.has(perm[swapCursor]))
      ) {
        swapCursor++;
      }
      if (swapCursor < total) {
        const tmp = perm[i];
        perm[i] = perm[swapCursor];
        perm[swapCursor] = tmp;
        swapCursor++;
      }
    }
  }

  yearTriviaCache.set(cacheKey, perm);
  return perm;
}

export function getDailyTriviaSet(count = 3, date = new Date(), options = {}) {
  const parsed = date instanceof Date ? date : new Date(date);
  const validDate = !Number.isNaN(parsed.getTime()) ? parsed : new Date();
  const useUtc = Boolean(options?.useUtc);

  const year = useUtc ? validDate.getUTCFullYear() : validDate.getFullYear();
  const month = useUtc ? validDate.getUTCMonth() : validDate.getMonth();
  const day = useUtc ? validDate.getUTCDate() : validDate.getDate();

  const dateKey = `${year}-${String(month + 1).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
  const dayOfYear = Math.round(
    (Date.UTC(year, month, day) - Date.UTC(year, 0, 0)) / MS_PER_DAY
  );

  const safeCount = Math.max(
    1,
    Math.min(triviaQuestions.length, Number.isFinite(count) ? Math.floor(count) : 3)
  );
  const perm = getYearTriviaPermutation(year, safeCount);
  const total = perm.length;
  const start = (dayOfYear - 1) * safeCount;

  const questions = [];
  const usedIndices = new Set();
  for (let k = 0; k < safeCount; k++) {
    const qIdx = perm[(start + k) % total];
    if (usedIndices.has(qIdx)) continue;
    usedIndices.add(qIdx);
    const entry = triviaQuestions[qIdx];
    questions.push({
      id: `trivia_${qIdx + 1}`,
      question: entry.question,
      options: entry.options,
      answerIndex: entry.answerIndex,
      explanation: entry.explanation,
    });
  }

  return {
    dateKey,
    dayOfYear,
    year,
    questions,
  };
}

export function getDailyTrivia(date = new Date(), options = {}) {
  const set = getDailyTriviaSet(1, date, options);
  return set.questions[0] || null;
}
